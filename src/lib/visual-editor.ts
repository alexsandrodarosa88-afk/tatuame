export const VISUAL_FONTS = {
  original: "",
  manrope: '"Manrope", sans-serif',
  fraunces: '"Fraunces", Georgia, serif',
  arial: 'Arial, sans-serif',
  georgia: 'Georgia, serif',
  courier: '"Courier New", monospace',
} as const;

export type VisualElement = {
  text?: string;
  image?: string;
  font?: keyof typeof VISUAL_FONTS;
  color?: string;
  background?: string;
  align?: "left" | "center" | "right";
  size?: number;
  weight?: number;
  order?: number;
  width?: number;
  spacing?: number;
};

export const validColor = (value?: string) => /^#[0-9a-f]{6}$/i.test(value ?? "");
export const validImage = (value?: string) => {
  if (!value) return false;
  try { return new URL(value).protocol === "https:"; } catch { return false; }
};
const bounded = (value: unknown, min: number, max: number) => typeof value === "number" && Number.isFinite(value) && value >= min && value <= max;

export function visualDeclarations(value: VisualElement) {
  const css: string[] = [];
  if (value.font && Object.hasOwn(VISUAL_FONTS, value.font) && VISUAL_FONTS[value.font]) css.push(`font-family:${VISUAL_FONTS[value.font]}!important`);
  if (validColor(value.color)) css.push(`--visual-text:${value.color};color:var(--visual-text)!important`);
  if (validColor(value.background)) css.push(`--visual-background:${value.background};background-color:var(--visual-background)!important`);
  if (["left", "center", "right"].includes(value.align ?? "")) css.push(`text-align:${value.align}!important`);
  if (bounded(value.size, 8, 96)) css.push(`font-size:${value.size}px!important;line-height:1.3!important;overflow-wrap:anywhere`);
  if (bounded(value.weight, 300, 900)) css.push(`font-weight:${value.weight}!important`);
  if (bounded(value.order, -100, 100)) css.push(`order:${value.order}!important`);
  if (bounded(value.width, 10, 100)) css.push(`width:${value.width}%!important;max-width:100%`);
  if (bounded(value.spacing, 0, 120)) css.push(`margin-block:${value.spacing}px!important`);
  return css.join(";");
}

/** Only structural selectors generated by our editor are accepted. */
export const validSelector = (selector: string) => /^\[data-visual-id="[a-z0-9_-]+"\]$/.test(selector);